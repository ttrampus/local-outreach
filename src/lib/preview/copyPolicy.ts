// What the generated copy is allowed to assert about a real business.
//
// These pages go to the owner of an existing business and, once bought, become
// that business's public website. Every sentence on them is a statement the
// business is making about itself — so the generator must never write a claim
// nobody has verified.
//
// The failure this exists to stop: the model was told to "weave the specifics
// customers praise into the copy", and it turned review fragments into
// declarative marketing claims — e.g. "Tamara and Karin will tell you what
// actually works for your face shape and hair structure". Nobody said that. It
// reads strange, it is unverifiable, and the owner is the one who would have to
// stand behind it.
//
// The line: STRUCTURE and IDENTITY may be specific (real name, real city, real
// photos, real hours, real rating, verbatim review quotes). CLAIMS must stay
// broad — the kind of copy any good site in the category could carry. The
// genuinely specific material gets added later, by the owner, once they are a
// customer and can actually be asked.
export const COPY_POLICY = `COPY RULES — these override any instinct to make the writing feel bespoke:

Facts you may state (these are verified from Google):
- the business name, its category, and its city or neighbourhood
- the address, phone number and opening hours exactly as given
- the star rating and review count exactly as given
- staff first names ONLY as a plain list (e.g. "Frizerji: Tamara, Karin") — never attached to a claim about what they do, say, specialise in or promise
- customer reviews quoted VERBATIM and clearly presented as customer reviews

Never write:
- any claim about how the business works, its method, philosophy, process or approach
- what a customer will experience, be told, or receive ("they will advise you on...", "you will leave feeling...")
- specifics nobody stated: years in business, staff numbers, opening times beyond those given, prices, guarantees, awards, certifications, brands used, techniques offered
- superlatives as fact ("the best in town", "the leading salon")
- anything inferred from a review and then restated as if the business said it

Tone: write broad, warm, professional marketing copy of the kind any good site in
this category could carry. A short evocative slogan is welcome. Being generic is
CORRECT here — a generic true sentence is always better than a specific invented
one. If you are unsure whether something is verified, leave it out.`;
